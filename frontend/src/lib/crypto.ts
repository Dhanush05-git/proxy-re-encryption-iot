/**
 * crypto.ts
 * 
 * Browser-side cryptographic helpers.
 * NOTE: For this demo, private keys are sent to the backend for PRE operations
 * (trusted-client demo model). In production, private keys NEVER leave the client.
 */

/** Encode bytes to base64 */
export function bytesToBase64(bytes: Uint8Array): string {
  let binary = '';
  for (let i = 0; i < bytes.length; i++) {
    binary += String.fromCharCode(bytes[i]);
  }
  return btoa(binary);
}

/** Decode base64 to bytes */
export function base64ToBytes(b64: string): Uint8Array {
  const binary = atob(b64);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) {
    bytes[i] = binary.charCodeAt(i);
  }
  return bytes;
}

/** Truncate a base64/hex string for display */
export function truncateKey(key: string, chars = 24): string {
  if (!key) return '';
  if (key.length <= chars * 2 + 3) return key;
  return key.slice(0, chars) + '...' + key.slice(-chars);
}

/**
 * Derive an AES-GCM key from a password using PBKDF2.
 * Used to encrypt the private key stored in localStorage.
 */
async function deriveKeyFromPassword(
  password: string,
  salt: Uint8Array
): Promise<CryptoKey> {
  const encoder = new TextEncoder();
  const keyMaterial = await window.crypto.subtle.importKey(
    'raw',
    encoder.encode(password),
    'PBKDF2',
    false,
    ['deriveKey']
  );
  return window.crypto.subtle.deriveKey(
    {
      name: 'PBKDF2',
      salt: salt.buffer as ArrayBuffer,
      iterations: 100_000,
      hash: 'SHA-256',
    },
    keyMaterial,
    { name: 'AES-GCM', length: 256 },
    false,
    ['encrypt', 'decrypt']
  );
}

/** Encrypt a private key string with a password, store to localStorage */
export async function storePrivateKey(
  storageKey: string,
  secretKeyB64: string,
  password: string
): Promise<void> {
  const salt = window.crypto.getRandomValues(new Uint8Array(16));
  const iv = window.crypto.getRandomValues(new Uint8Array(12));
  const key = await deriveKeyFromPassword(password, salt);
  const encoder = new TextEncoder();
  const encrypted = await window.crypto.subtle.encrypt(
    { name: 'AES-GCM', iv },
    key,
    encoder.encode(secretKeyB64)
  );
  const payload = {
    salt: bytesToBase64(salt),
    iv: bytesToBase64(iv),
    data: bytesToBase64(new Uint8Array(encrypted)),
  };
  localStorage.setItem(storageKey, JSON.stringify(payload));
}

/** Decrypt a private key from localStorage using a password */
export async function loadPrivateKey(
  storageKey: string,
  password: string
): Promise<string | null> {
  const raw = localStorage.getItem(storageKey);
  if (!raw) return null;
  try {
    const { salt, iv, data } = JSON.parse(raw);
    const key = await deriveKeyFromPassword(password, base64ToBytes(salt));
    const decrypted = await window.crypto.subtle.decrypt(
      { name: 'AES-GCM', iv: base64ToBytes(iv).buffer as ArrayBuffer },
      key,
      base64ToBytes(data).buffer as ArrayBuffer
    );
    return new TextDecoder().decode(decrypted);
  } catch {
    return null;
  }
}

/**
 * Generate a random 32-byte key pair (for demo).
 * Returns base64-encoded secret and public key.
 * Actual PRE keypairs are generated by the backend using Python umbral.
 */
export function generateLocalKeyPair(): { secretKeyB64: string; publicKeyB64: string } {
  const secretBytes = window.crypto.getRandomValues(new Uint8Array(32));
  const publicBytes = window.crypto.getRandomValues(new Uint8Array(33));
  return {
    secretKeyB64: bytesToBase64(secretBytes),
    publicKeyB64: bytesToBase64(publicBytes),
  };
}

/**
 * Encrypt data with AES-256-GCM in the browser (for local preview only).
 * Returns { ciphertext, nonce } both as base64.
 */
export async function encryptFile(
  data: Uint8Array,
  dekB64: string
): Promise<{ ciphertextB64: string; nonceB64: string }> {
  const dekBytes = base64ToBytes(dekB64);
  const key = await window.crypto.subtle.importKey(
    'raw',
    dekBytes.buffer as ArrayBuffer,
    { name: 'AES-GCM' },
    false,
    ['encrypt']
  );
  const nonce = window.crypto.getRandomValues(new Uint8Array(12));
  const ciphertext = await window.crypto.subtle.encrypt(
    { name: 'AES-GCM', iv: nonce },
    key,
    data as unknown as BufferSource
  );
  return {
    ciphertextB64: bytesToBase64(new Uint8Array(ciphertext)),
    nonceB64: bytesToBase64(nonce),
  };
}

/**
 * Decrypt data with AES-256-GCM in the browser.
 */
export async function decryptFile(
  encryptedB64: string,
  nonceB64: string,
  dekB64: string
): Promise<Uint8Array> {
  const dekBytes = base64ToBytes(dekB64);
  const key = await window.crypto.subtle.importKey(
    'raw',
    dekBytes.buffer as ArrayBuffer,
    { name: 'AES-GCM' },
    false,
    ['decrypt']
  );
  const plaintext = await window.crypto.subtle.decrypt(
    { name: 'AES-GCM', iv: base64ToBytes(nonceB64).buffer as ArrayBuffer },
    key,
    base64ToBytes(encryptedB64).buffer as ArrayBuffer
  );
  return new Uint8Array(plaintext);
}
